  const F = 93.27191 + 483202.017538 * T - 0.0036825 * T * T + (T ** 3) / 327270;
  const Om = 125.04452 - 1934.136261 * T + 0.0020708 * T * T + (T ** 3) / 450000;

  // [D, M, M', F, Ω, 계수(0.0001″), 계수의 T 항]
