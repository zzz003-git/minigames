const series = (terms, tau) => terms.reduce((s, [a, b, c]) => s + a * Math.cos(b + c * tau), 0);

/** 지구의 일심 황경(도) — VSOP87 절삭 */
function earthLongitude(tau) {
  const l =
    (series(L0, tau) +
      series(L1, tau) * tau +
      series(L2, tau) * tau ** 2 +
      series(L3, tau) * tau ** 3 +
      series(L4, tau) * tau ** 4 +
      series(L5, tau) * tau ** 5) *
    1e-8;
  return mod360((l * 180) / Math.PI);
}

/** 지구–태양 거리 (AU) — 광행차에 쓴다 */
function earthRadius(tau) {
  return (
    (series(R0, tau) +
      series(R1, tau) * tau +
      series(R2, tau) * tau ** 2 +
      series(R3, tau) * tau ** 3 +
      series(R4, tau) * tau ** 4) *
    1e-8
  );
}

