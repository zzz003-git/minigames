/** 그레고리력 → 율리우스일 (UT) */
export function toJD(y, m, d, h = 0, mi = 0) {
  let Y = y, M = m;
  if (M <= 2) { Y -= 1; M += 12; }
  const A = Math.floor(Y / 100);
  const B = 2 - A + Math.floor(A / 4);
  return (
    Math.floor(365.25 * (Y + 4716)) + Math.floor(30.6001 * (M + 1)) + d + B - 1524.5 +
    (h + mi / 60) / 24
  );
}

/** 율리우스일(UT) → { y, m, d, h, mi } (KST 로 바꾸려면 +9h 를 미리 더한다) */
export function fromJD(jd) {
  const z = Math.floor(jd + 0.5);
  const f = jd + 0.5 - z;
  let A = z;
  if (z >= 2299161) {
    const alpha = Math.floor((z - 1867216.25) / 36524.25);
    A = z + 1 + alpha - Math.floor(alpha / 4);
  }
  const B = A + 1524;
  const C = Math.floor((B - 122.1) / 365.25);
  const D = Math.floor(365.25 * C);
  const E = Math.floor((B - D) / 30.6001);
  const dayF = B - D - Math.floor(30.6001 * E) + f;
  const day = Math.floor(dayF);
  const m = E < 14 ? E - 1 : E - 13;
  const y = m > 2 ? C - 4716 : C - 4715;
  const frac = dayF - day;
  const totalMin = Math.round(frac * 1440);
  return { y, m, d: day + Math.floor(totalMin / 1440), h: Math.floor((totalMin % 1440) / 60), mi: totalMin % 60 };
}

/**
 * 태양 황경이 `target` 도에 닿는 순간을 찾는다 (KST).
 *
 * 뉴턴법으로 좁힌다 — 태양은 하루에 약 0.9856° 움직이므로 수렴이 빠르다.
 *
 * @param {number} jdGuess 시작 추정 율리우스일 (UT)
 * @param {number} target 목표 황경 (0~345, 15° 배수)
 * @returns {{ jdUT:number, kst:{y,m,d,h,mi} }}
 */
export function findTerm(jdGuess, target) {
  let jd = jdGuess;
  for (let i = 0; i < 12; i++) {
    const year = fromJD(jd).y;
    const jdTT = jd + deltaT(year) / 86400;
    let diff = sunApparentLongitude(jdTT) - target;
    // 0°/360° 경계를 건너지 않게 접는다
    if (diff > 180) diff -= 360;
    if (diff < -180) diff += 360;
    if (Math.abs(diff) < 1e-8) break;
    jd -= diff / 0.9856473; // 하루당 진행 도수
  }
  // KST = UT + 9h
  return { jdUT: jd, kst: fromJD(jd + 9 / 24) };
}

