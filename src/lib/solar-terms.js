/**
 * 🌤️ 절기 계산 — 태양 겉보기 황경이 15° 배수에 닿는 순간
 * ==========================================================================
 *
 * 확정 문서: docs/saju-calendar.md
 *
 * ── 왜 계산인가 ──────────────────────────────────────────────────────────
 * KASI 24절기 API 는 **2000~2028년만** 준다(실측 확인). 사주는 출생 연도의 절기가
 * 필요하고 타깃이 20~65세(1961~2006년생)라 그 범위로는 대부분이 명식을 못 세운다.
 * 절기는 천문 계산으로 구할 수 있고 연도 제한이 없으므로 계산으로 간다.
 *
 * **검증은 KASI 가 준 2000~2028 구간 696건 전건 대조로 한다.** 정답지가 있는
 * 구간에서 다 맞으면 바깥 연도도 같은 알고리즘이라 신뢰할 근거가 된다.
 *
 * ── 필요한 정밀도 ────────────────────────────────────────────────────────
 * KASI 는 분 단위로 준다. 태양은 하루에 약 0.9856° 움직이므로 1분 = 약 0.000685°
 * = 2.5″ 다. 즉 **황경을 2.5″ 안쪽으로** 맞춰야 분이 어긋나지 않는다.
 *
 * 그래서 이렇게 쌓는다.
 *   VSOP87 절삭 급수 (Meeus 요약판)   황경 약 1″
 *   + FK5 보정 · 장동(章動) · 광행차   장동만 최대 17″(약 7분)라 빼면 안 된다
 *   + ΔT (TT↔UT)                       2000년 약 64초 — 분 단위 일치에 필요하다
 *
 * ── 왜 표로 굳히지 않았나 ────────────────────────────────────────────────
 * 원래는 표로 받아 굳히려 했는데 받을 표가 2000~2028 뿐이었다. 계산으로 만든 표를
 * 정적 포함하는 것이 결론이고, 이 파일은 **그 표를 만드는 도구**다. 런타임은
 * 여전히 표만 읽는다(외부 호출도 계산도 없다).
 */

