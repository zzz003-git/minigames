/** 절기 이름 → 태양 황경 (입춘 315°) */
export const termLongitude = (i) => (315 + i * 15) % 360;

/**
 * 한 해의 24절기를 전부 구한다.
 * @returns {Array<{ name:string, sun:number, at:string }>} at = 'YYYY-MM-DDTHH:MM' (KST)
 */
export function termsOfYear(year) {
  const out = [];
  const jan1 = toJD(year, 1, 1);

  for (let i = 0; i < 24; i++) {
    const sun = termLongitude(i);

    // 시작 추정은 **황경에서 직접 역산**한다. 1월 1일의 태양 황경이 약 280° 이므로
    // 목표까지의 각도를 하루 진행량으로 나누면 이틀 안쪽으로 들어온다.
    //
    // 달력상의 월로 추정하던 초안은 절기마다 손으로 짠 표를 썼는데, 몇 개가
    // **이웃 절기로 수렴해 하루가 통째로 어긋났다**(KASI 대조에서 -1440분으로 잡혔다).
    // 각도에서 역산하면 그 표 자체가 없어진다.
    const offsetDays = mod360(sun - 280) / 0.9856473;
    const { kst } = findTerm(jan1 + offsetDays, sun);

    out.push({
      name: TERM_NAMES[i],
      sun,
      at:
        `${kst.y}-${String(kst.m).padStart(2, "0")}-${String(kst.d).padStart(2, "0")}` +
        `T${String(kst.h).padStart(2, "0")}:${String(kst.mi).padStart(2, "0")}`,
    });
  }

  return out.sort((a, b) => a.at.localeCompare(b.at));
}
