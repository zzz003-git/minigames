// ══════════════════════════════════════════════════════════════
// ΔT (TT − UT) — 분 단위 일치에 필요하다
// ══════════════════════════════════════════════════════════════

/**
 * Espenak–Meeus 다항식. 우리가 쓰는 1930~2050 구간만 담는다.
 * 2005~2050 은 예측식이라 미래로 갈수록 불확실하지만, 절기가 분 단위로
 * 흔들릴 정도는 아니다(2050 예측 오차 수 초 수준).
 */
export function deltaT(year) {
  if (year < 1941) {
    const t = year - 1920;
    return 21.20 + 0.84493 * t - 0.076100 * t * t + 0.0020936 * t ** 3;
  }
  if (year < 1961) {
    const t = year - 1950;
    return 29.07 + 0.407 * t - (t * t) / 233 + (t ** 3) / 2547;
  }
  if (year < 1986) {
    const t = year - 1975;
    return 45.45 + 1.067 * t - (t * t) / 260 - (t ** 3) / 718;
  }
  if (year < 2005) {
    const t = year - 2000;
    return (
      63.86 + 0.3345 * t - 0.060374 * t * t + 0.0017275 * t ** 3 +
      0.000651814 * t ** 4 + 0.00002373599 * t ** 5
    );
  }
  if (year < 2050) {
    const t = year - 2000;
    return 62.92 + 0.32217 * t + 0.005589 * t * t;
  }
  const t = year - 1820;
  return -20 + 32 * (t / 100) ** 2 - 0.5628 * (2150 - year);
}

// ══════════════════════════════════════════════════════════════
// 태양 겉보기 황경
// ══════════════════════════════════════════════════════════════

const JD2000 = 2451545.0;

/** 율리우스일(TT) → 태양 겉보기 황경 (도) */
export function sunApparentLongitude(jdTT) {
  const T = (jdTT - JD2000) / 36525;
  const tau = T / 10;

  // 지구의 일심 황경 + 180° = 태양의 지심 황경
  let theta = mod360(earthLongitude(tau) + 180);

  // FK5 보정
  const lambdaPrime = theta - 1.397 * T - 0.00031 * T * T;
  theta += (-0.09033 / 3600) + 0; // ΔL (황위 항은 황경에 거의 영향 없음)
  theta += (-0.03916 / 3600) * (Math.cos(lambdaPrime * RAD) - Math.sin(lambdaPrime * RAD)) * 0;

  // 장동 + 광행차
  const dpsi = nutationLongitude(T);
  const R = earthRadius(tau);
  const aberration = -20.4898 / 3600 / R;

  return mod360(theta + dpsi + aberration);
}

