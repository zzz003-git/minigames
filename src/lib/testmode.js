/**
 * 테스트 모드 — 외부 테스터가 한도에 막히지 않게 하는 스위치
 * ==========================================================================
 *
 * 외부 테스터에게 빌드를 주면 **게임이 재미있는지 보기도 전에 한도에 막힙니다.**
 * 하루 3~5판이 설계값이라 10분이면 소진되고, 특히 IP 한도는 같은 사무실·집 와이파이를
 * 쓰는 테스터들이 **한 사람의 시청으로 다 같이 막힙니다**(동일 IP 하루 광고 20회).
 *
 * ── 스위치가 두 개인 이유 ────────────────────────────────────────────────
 * 이 한도들은 장식이 아니라 **어뷰징 방어**입니다. 프로덕션에서 꺼지면 광고 수익과
 * 순위표가 그대로 열립니다. 그래서 하나만 잘못 건드려서는 켜지지 않게 두 조건을
 * 모두 요구합니다.
 *
 *   TEST_MODE === "on"           명시적으로 켤 때만
 *   ENV_NAME  !== "production"   프로덕션 환경이 아닐 때만
 *
 * 프로덕션 `wrangler.jsonc` 는 `ENV_NAME: "production"` 을 박아 두므로, 누가
 * `TEST_MODE` 를 켜도 프로덕션에서는 아무 일도 일어나지 않습니다. 반대로 스테이징은
 * `ENV_NAME: "staging"` 이라 `TEST_MODE` 한 줄로 켜집니다.
 *
 * `ENV_NAME` 이 없는 환경(로컬 `wrangler dev`)에서는 `TEST_MODE` 만으로 켜집니다 —
 * 로컬은 프로덕션이 아니기 때문입니다.
 *
 * ── 푸는 것과 풀지 않는 것 ───────────────────────────────────────────────
 * 푸는 것은 **날짜로 리셋되는 한도**뿐입니다. 하루를 기다려야 풀리는 것들이라
 * 테스트를 막습니다.
 *
 *   · 게임별 하루 도전 기회 (consumeAttempt)
 *   · 게임별 하루 광고 보상 횟수 (adAttemptsPerDay · AD_TRIGGERS.perDay)
 *   · 동일 IP 하루 광고 시청 20회 (assertIpAdLimit)
 *
 * **판·세션 단위 한도는 풀지 않습니다.** 1런당 이어하기 2회, 숫자야구 1게임당 광고
 * 3회는 판을 새로 시작하면 리셋되므로 테스트를 막지 않고, 오히려 그 한도가 걸리는
 * 순간의 화면이 테스트 대상입니다.
 */

/**
 * @param {{ TEST_MODE?: string, ENV_NAME?: string }} env
 * @returns {boolean}
 */
export const isTestMode = (env) =>
  env?.TEST_MODE === "on" && env?.ENV_NAME !== "production";
