-- ✍✍ 트랙 칸 (`system/yourstory2_track_separation.md` §1 · YS2 개발 회신 05)
--
-- ── ⚠ 이 파일은 **프로덕션에 이미 손으로 적용된 변경**이다 ────────────────
-- `track` 칸은 2026-08-26 에 마이그레이션 파일 없이 프로덕션 D1 에 직접 들어갔고
-- (45행 `ys1` 백필까지 됨), 그래서 `d1_migrations` 에는 0023 까지만 남아 있다.
-- 비어 있는 스테이징에 0001~ 을 순서대로 적용하면 **스테이징에만 이 칸이 없어**
-- 두 환경의 스키마가 갈린다. 그 갈림을 여기서 닫는다.
--
--   · 스테이징(빈 DB) — 그냥 적용된다
--   · 프로덕션        — 칸이 이미 있으므로 **이 파일을 적용하면 실패한다.**
--                       적용 대신 「이미 반영됨」으로 기록만 넣는다:
--                         INSERT INTO d1_migrations (name, applied_at)
--                         VALUES ('0024_ys_track.sql', CURRENT_TIMESTAMP);
--                       (배포 목록의 순서 ①. 이 줄을 넣기 전에 0025 를 적용하면
--                        0024 가 먼저 실행되어 배포가 통째로 멈춘다)
--
-- ── 트랙은 값 하나다 ─────────────────────────────────────────────────────
-- 경로·화풍 문자열·캐릭터 유무로 트랙을 추정하지 않는다(트랙 정본 §2). 읽는 쪽은
-- PC 의 `ys_track.track_of` 한 함수이고, 클라우드에서는 접수 핸들러가 채운다.
ALTER TABLE ys_order ADD COLUMN track TEXT;

-- 이미 만들어진 주문은 전부 YS1 이다. **빈 값으로 두지 않는다** — 빈 값이 결함을
-- 가린 사고가 이 프로젝트의 반복 유형이라, 과거분은 지금 이름을 붙여 둔다
UPDATE ys_order SET track = 'ys1' WHERE track IS NULL;
