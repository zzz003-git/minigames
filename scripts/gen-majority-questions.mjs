/** 서버가 배정에 쓰는 최소 문항 수. 한 판에 최대 6문항이 나가므로 여유가 필요합니다. */
const MINIMUM = 40;
const MAX_PROMPT = 24; // 7초 안에 읽혀야 합니다
const MAX_OPTION = 12; // 보기 버튼 한 줄

const sqlQuote = (s) => `'${s.replace(/'/g, "''")}'`;
const len = (s) => [...s].length;

const rows = [];
const seenPrompt = new Set();
const counts = {};

for (const [topic, list] of GROUPS) {
  for (const [rawPrompt, rawA, rawB] of list) {
    const prompt = rawPrompt.trim();
    const a = rawA.trim();
    const b = rawB.trim();

    if (seenPrompt.has(prompt)) throw new Error(`중복 질문: ${prompt}`);
    seenPrompt.add(prompt);

    if (a === b) throw new Error(`보기가 같습니다: ${prompt}`);
    if (len(prompt) > MAX_PROMPT) throw new Error(`질문이 너무 깁니다(${len(prompt)}자): ${prompt}`);
    for (const opt of [a, b]) {
      if (len(opt) > MAX_OPTION) throw new Error(`보기가 너무 깁니다(${len(opt)}자): ${opt}`);
    }

    rows.push(
      `  (${sqlQuote(topic)}, ${sqlQuote(prompt)}, ${sqlQuote(a)}, ${sqlQuote(b)}, 1, ${"CAST(strftime('%s','now') AS INTEGER) * 1000"})`,
    );
    counts[topic] = (counts[topic] ?? 0) + 1;
  }
}

if (rows.length < MINIMUM) {
  throw new Error(`문항이 부족합니다: ${rows.length} / 최소 ${MINIMUM}`);
}

const summary = Object.entries(counts)
  .map(([t, n]) => `${t} ${n}`)
  .join(" / ");

const header = `-- ⑮ 다들 뭐 골랐을까 — 문항 은행 시드
-- 이 파일은 scripts/gen-majority-questions.mjs 가 생성합니다. 직접 수정하지 마세요.
-- 문항을 추가·수정할 때는 스크립트를 고치고 \`node scripts/gen-majority-questions.mjs\` 를 다시 실행하세요.
--
-- 수량: ${summary} = 총 ${rows.length}문항
-- 표(snap/live)는 0 에서 시작합니다. 표본이 모이기 전까지 그 문항은 "집계 중" 으로
-- 판정 없이 통과 처리되고 점수도 0 입니다 (없는 비율을 지어내지 않습니다).

INSERT INTO majority_questions (topic, prompt, option_a, option_b, active, created_at) VALUES
`;

const outPath = join(ROOT, "migrations", "0008_seed_majority_questions.sql");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, header + rows.join(",\n") + ";\n", "utf8");

