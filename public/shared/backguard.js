/**
 * 뒤로가기 가드 — 판이 도는 중에 화면을 떠나지 않게 한다
 * ==========================================================================
 *
 * iOS Safari 는 **왼쪽 가장자리에서 오른쪽으로 밀면 이전 화면으로 갑니다.** 손가락으로
 * 끄는 게임에서는 판 위를 쓸어 담는 동작이 곧 그 제스처가 됩니다 — 아이폰 16 Pro 에서
 * 실제로 나갔습니다(2026-09-08).
 *
 * ⚠ **제스처 자체는 못 막습니다.** 좌우 여백을 24px 로 넓혀 가장자리 띠를 피해 보았지만
 *    실기기에서 그대로 넘어갔습니다. 그래서 **가더라도 페이지를 안 떠나게** 합니다 —
 *    방문 기록을 한 칸 밀어 넣어 두고, 뒤로가기가 오면 다시 밀어 넣습니다.
 *
 * ── 이 파일의 전부는 「갇히지 않게 하는 것」입니다 ────────────────────────
 * 붙잡기만 하고 놓아주는 자리를 빠뜨리면 **나가기를 눌러도 못 나갑니다.** 그래서
 *   · 판이 **도는 중일 때만** 붙잡습니다. 결과 화면 등에서는 그냥 보냅니다
 *   · `release()` 는 **나가기를 확정한 한 곳에서만** 부르고, 부른 뒤 **바로 실제로 이동**합니다
 *   · `history.go(-2)` 를 쓰지 않습니다 — 게임 링크로 바로 들어온 이용자에게는 이전 기록이
 *     없어 갇힙니다. 기록이 한 칸 더 쌓이는 것은 감수합니다
 *
 * 지금은 ㉛ 클로버만 씁니다. 드래그로 조작하는 게임이 넷 더 있지만
 * (⑱ 와르르 받기 · ⑳ 슥슥 긁기 · ㉚ 쭉 · ㉘ 톡톡) **각각 확인한 뒤에 켭니다.**
 * ==========================================================================
 */

/**
 * @param {{ isPlaying: () => boolean, onCaught: () => void, onLeave: () => void }} opts
 *   isPlaying — 지금 판이 도는 중인가. 참일 때만 붙잡습니다
 *   onCaught  — 붙잡았을 때(=나가기 확인을 띄울 자리). 판은 계속 돕니다
 *   onLeave   — 붙잡지 않고 내보낼 때. 여기서 실제 이동을 합니다
 * @returns {{ arm: () => void, release: () => void, armed: () => boolean }}
 */
export function createBackGuard({ isPlaying, onCaught, onLeave }) {
  let armed = false;

  const push = () => {
    try {
      history.pushState({ cvGuard: 1 }, "");
      return true;
    } catch {
      // 기록을 못 밀어 넣는 환경이면 가드를 켜지 않습니다 — 켠 척하면
      // 뒤로가기를 잡지도 못하면서 나가기만 막는 최악이 됩니다.
      return false;
    }
  };

  addEventListener("popstate", () => {
    if (!armed) return;

    if (isPlaying()) {
      push(); // 다시 밀어 넣어 다음 뒤로가기도 잡습니다
      onCaught();
      return;
    }
    armed = false;
    onLeave();
  });

  return {
    /** 판 시작에서 부릅니다. 두 번 불러도 기록은 한 칸만 쌓입니다 */
    arm() {
      if (armed) return;
      armed = push();
    },
    /** 나가기를 확정한 자리에서만. 부른 **직후에 실제 이동**을 하십시오 */
    release() {
      armed = false;
    },
    armed: () => armed,
  };
}
